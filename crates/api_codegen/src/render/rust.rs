use std::fmt::Write;

use crate::node::{
    EnumNode, MethodNode, Node, NotificationNode, PrimitiveType, StructNode, TypeNode,
};

#[must_use]
pub fn render_rust(nodes: &[Node]) -> String {
    let mut output = Vec::new();
    output.push("// This file is automatically generated. Do not edit manually.".to_owned());
    output.push(String::new());

    for node in nodes {
        match node {
            Node::Type(TypeNode::Struct(node)) => output.push(render_struct(node)),
            Node::Type(TypeNode::Enum(node)) => output.push(render_enum(node)),
            Node::Type(_) => {}
            Node::Method(node) => {
                if let Some(rendered) = render_type(&node.params) {
                    output.push(rendered);
                }
                if let Some(rendered) = render_type(&node.result) {
                    output.push(rendered);
                }
                output.push(render_method(node));
            }
            Node::Notification(node) => {
                if let Some(rendered) = render_type(&node.params) {
                    output.push(rendered);
                }
                output.push(render_notification(node));
            }
        }
    }

    output.join("\n")
}

fn render_type(this: &TypeNode) -> Option<String> {
    if let TypeNode::Struct(strukt) = &this {
        Some(render_struct(strukt))
    } else if let TypeNode::Enum(enum_) = &this {
        Some(render_enum(enum_))
    } else if let TypeNode::Array(array) = &this {
        render_type(array.as_ref())
    } else if let TypeNode::Map(value) = &this {
        render_type(value.as_ref())
    } else {
        None
    }
}

fn render_struct(this: &StructNode) -> String {
    let mut lines = Vec::new();
    let default_impl = render_default_impl(this);
    let default_helpers = render_default_helpers(this);

    for field in &this.fields {
        if let Some(rendered) = render_type(&field.typ) {
            lines.push(rendered);
        }
    }

    for doc in &this.doc {
        lines.push(format!("/// {doc}"));
    }
    lines.push(
        "#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]".to_owned(),
    );
    lines.push("#[serde(rename_all = \"kebab-case\")]".to_owned());
    if default_impl.is_some() {
        lines.push("#[serde(default)]".to_owned());
    }
    lines.push("#[allow(missing_copy_implementations)]".to_owned());
    lines.push(format!("pub struct {} {{", this.name));

    for (index, field) in this.fields.iter().enumerate() {
        if let Some(description) = &field.description {
            lines.push(format!("    /// {description}"));
        }

        let rust_name = rust_field_name(&field.name);
        let field_type = render_type_node(&field.typ);
        let serde_attributes = rust_field_serde_attributes(field, index, this);
        if field.required {
            if !serde_attributes.is_empty() {
                lines.push(format!("    #[serde({})]", serde_attributes.join(", ")));
            }
            lines.push(format!("    pub {rust_name}: {field_type},"));
        } else {
            lines.push(format!(
                "    #[serde({})]\n    pub {rust_name}: Option<{field_type}>,",
                serde_attributes.join(", ")
            ));
        }
    }

    lines.push("}\n".to_owned());
    if let Some(default_helpers) = default_helpers {
        lines.push(default_helpers);
    }
    if let Some(default_impl) = default_impl {
        lines.push(default_impl);
    }
    lines.join("\n")
}

fn rust_field_serde_attributes(
    field: &crate::node::FieldNode,
    index: usize,
    strukt: &StructNode,
) -> Vec<String> {
    let mut attributes = Vec::new();
    if field.default.is_some() {
        attributes.push(format!(
            "default = \"{}::__serde_default_{index}\"",
            strukt.name
        ));
    } else if !field.required {
        attributes.push("default".to_owned());
    }

    if !field.required {
        attributes.push("skip_serializing_if = \"Option::is_none\"".to_owned());
    }
    if matches!(field.typ, TypeNode::Primitive(PrimitiveType::Bytes)) {
        attributes.push(format!(
            "with = \"{}\"",
            bytes_serde_adapter(field.required)
        ));
    }
    attributes
}

fn render_default_helpers(this: &StructNode) -> Option<String> {
    let mut methods = Vec::new();
    for (index, field) in this.fields.iter().enumerate() {
        let Some(default) = &field.default else {
            continue;
        };
        let value = rust_default_value(&field.typ, default)
            .expect("schema defaults are validated during parsing");
        let (return_type, value) = if field.required {
            (render_type_node(&field.typ), value)
        } else {
            (
                format!("Option<{}>", render_type_node(&field.typ)),
                format!("Some({value})"),
            )
        };
        methods.push(format!(
            "    fn __serde_default_{index}() -> {return_type} {{\n        {value}\n    }}"
        ));
    }

    if methods.is_empty() {
        return None;
    }

    Some(format!("impl {} {{\n{}\n}}", this.name, methods.join("\n")))
}

fn render_default_impl(this: &StructNode) -> Option<String> {
    if !this.fields.iter().any(|field| field.default.is_some()) {
        return None;
    }

    let mut fields = Vec::new();
    for field in &this.fields {
        let value = match &field.default {
            Some(value) => {
                let value = rust_default_value(&field.typ, value)
                    .expect("schema defaults are validated during parsing");
                if field.required {
                    value
                } else {
                    format!("Some({value})")
                }
            }
            None if !field.required => "None".to_owned(),
            None => return None,
        };
        fields.push(format!(
            "            {}: {value},",
            rust_field_name(&field.name)
        ));
    }

    Some(format!(
        "impl Default for {} {{\n    fn default() -> Self {{\n        Self {{\n{}\n        }}\n    }}\n}}",
        this.name,
        fields.join("\n")
    ))
}

fn rust_default_value(typ: &TypeNode, value: &serde_json::Value) -> Option<String> {
    match typ {
        TypeNode::Primitive(PrimitiveType::Boolean) => {
            value.as_bool().map(|value| value.to_string())
        }
        TypeNode::Primitive(PrimitiveType::Integer) => {
            value.as_i64().map(|value| value.to_string())
        }
        TypeNode::Primitive(PrimitiveType::UnsignedInteger) => {
            value.as_u64().map(|value| value.to_string())
        }
        TypeNode::Primitive(PrimitiveType::Number) => value.as_f64().map(|value| {
            let value = value.to_string();
            if value.contains(['.', 'e', 'E']) {
                value
            } else {
                format!("{value}.0")
            }
        }),
        TypeNode::Primitive(PrimitiveType::String) => value
            .as_str()
            .and_then(|value| serde_json::to_string(value).ok())
            .map(|value| format!("Box::<str>::from({value})")),
        TypeNode::Array(inner) => value.as_array().and_then(|values| {
            values
                .iter()
                .map(|value| rust_default_value(inner, value))
                .collect::<Option<Vec<_>>>()
                .map(|values| format!("vec![{}]", values.join(", ")))
        }),
        TypeNode::Enum(enum_) => {
            let value = value.as_str()?;
            let variant = enum_
                .variants
                .iter()
                .find(|variant| variant.value == value)?;
            Some(format!("{}::{}", enum_.name, variant.name))
        }
        _ => None,
    }
}

fn render_enum(this: &EnumNode) -> String {
    if this.tag.is_some() {
        return render_tagged_enum(this);
    }

    let mut lines = Vec::new();
    if let Some(description) = &this.description {
        lines.push(format!("/// {description}"));
    }
    lines.push(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]"
            .to_owned(),
    );
    lines.push(format!("pub enum {} {{", this.name));
    for variant in &this.variants {
        if let Some(description) = &variant.description {
            lines.push(format!("    /// {description}"));
        }
        lines.push(format!(
            "    #[serde(rename = \"{}\")]\n    {},",
            variant.value, variant.name
        ));
    }
    lines.push("}\n".to_owned());
    lines.join("\n")
}

fn render_tagged_enum(this: &EnumNode) -> String {
    let mut lines = Vec::new();

    let tag = this.tag.as_deref().unwrap_or_default();
    for variant in &this.variants {
        for field in &variant.fields {
            if let Some(rendered) = render_type(&field.typ) {
                lines.push(rendered);
            }
        }
    }

    for doc in &this.doc {
        lines.push(format!("/// {doc}"));
    }
    lines.push(
        "#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]".to_owned(),
    );
    lines.push(format!(
        "#[serde(tag = \"{tag}\", rename_all = \"kebab-case\", rename_all_fields = \"kebab-case\")]"
    ));
    lines.push(format!("pub enum {} {{", this.name));

    for variant in &this.variants {
        lines.push(format!(
            "    #[serde(rename = \"{}\")]\n    {} {{",
            variant.value, variant.name
        ));
        for field in &variant.fields {
            if let Some(description) = &field.description {
                lines.push(format!("        /// {description}"));
            }
            let rust_name = rust_field_name(&field.name);
            let field_type = render_type_node(&field.typ);
            if field.required {
                if matches!(field.typ, TypeNode::Primitive(PrimitiveType::Bytes)) {
                    lines.push(format!(
                        "        #[serde(with = \"{}\")]",
                        bytes_serde_adapter(true)
                    ));
                }
                lines.push(format!("        {rust_name}: {field_type},"));
            } else if matches!(field.typ, TypeNode::Primitive(PrimitiveType::Bytes)) {
                lines.push(format!(
                    "        #[serde(default, skip_serializing_if = \"Option::is_none\", with = \"{}\")]\n        {rust_name}: Option<{field_type}>,",
                    bytes_serde_adapter(false)
                ));
            } else {
                lines.push(format!(
                    "        #[serde(default, skip_serializing_if = \"Option::is_none\")]\n        {rust_name}: Option<{field_type}>,"
                ));
            }
        }
        lines.push("    },".to_owned());
    }

    lines.push("}\n".to_owned());
    lines.join("\n")
}

fn render_method(this: &MethodNode) -> String {
    format!(
        "impl Method for {} {{\n    const NAME: &'static str = \"{}\";\n    type Result = {};\n}}\n",
        this.name,
        this.method_name,
        render_type_node(&this.result)
    )
}

fn render_notification(this: &NotificationNode) -> String {
    let mut lines = String::new();

    writeln!(lines, "impl Notification for {} {{", this.name).unwrap();
    writeln!(
        lines,
        "    const NAME: &'static str = \"{}\";",
        this.method_name
    )
    .unwrap();
    writeln!(lines, "}}").unwrap();
    lines
}

fn render_type_node(type_node: &TypeNode) -> String {
    match type_node {
        TypeNode::Struct(node) => node.name.clone(),
        TypeNode::Enum(node) => node.name.clone(),
        TypeNode::Primitive(PrimitiveType::String) => "Box<str>".to_owned(),
        TypeNode::Primitive(PrimitiveType::Uuid) => "uuid::Uuid".to_owned(),
        TypeNode::Primitive(PrimitiveType::Bytes) => "Box<[u8]>".to_owned(),
        TypeNode::Primitive(PrimitiveType::Uri) => "url::Url".to_owned(),
        TypeNode::Primitive(PrimitiveType::Integer) => "i64".to_owned(),
        TypeNode::Primitive(PrimitiveType::UnsignedInteger) => "usize".to_owned(),
        TypeNode::Primitive(PrimitiveType::Number) => "f64".to_owned(),
        TypeNode::Primitive(PrimitiveType::Boolean) => "bool".to_owned(),
        TypeNode::Array(inner) => format!("Vec<{}>", render_type_node(inner)),
        TypeNode::Map(value) => {
            format!(
                "std::collections::HashMap<String, {}>",
                render_type_node(value)
            )
        }
        TypeNode::Reference(name) => name.clone(),
        TypeNode::Any => "Value".to_owned(),
        TypeNode::Unit => "()".to_owned(),
    }
}

fn bytes_serde_adapter(required: bool) -> &'static str {
    if required {
        "::serde_with::As::<::serde_with::base64::Base64>"
    } else {
        "::serde_with::As::<Option<::serde_with::base64::Base64>>"
    }
}

fn rust_field_name(name: &str) -> String {
    let mut result = String::new();
    let mut prev_was_separator = false;

    for ch in name.chars() {
        if matches!(ch, '-' | '_' | ' ' | '.' | '/' | ':') {
            if !result.is_empty() && !prev_was_separator {
                result.push('_');
                prev_was_separator = true;
            }
            continue;
        }

        if ch.is_ascii_uppercase() && !result.is_empty() && !prev_was_separator {
            let last = result.chars().last().unwrap_or_default();
            if last.is_ascii_lowercase() || last.is_ascii_digit() {
                result.push('_');
            }
        }

        result.push(ch.to_ascii_lowercase());
        prev_was_separator = false;
    }

    while result.starts_with('_') {
        result.remove(0);
    }
    while result.ends_with('_') {
        result.pop();
    }

    if result.is_empty() {
        return "value".to_owned();
    }

    match result.as_str() {
        "type" => "r#type".to_owned(),
        "self" => "self_".to_owned(),
        _ => result,
    }
}
